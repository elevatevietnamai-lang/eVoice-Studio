"""Karaoke (word-highlight) ASS builder for dub hardsub export.

Pure text-in/text-out: no ffmpeg, no models, no filesystem. ``build_ass``
turns subtitle cues into an ASS script whose lines carry ``\\k``/``\\kf``
karaoke tags, so ffmpeg's ``ass=`` filter burns a word-by-word highlight
sweep instead of the static line the SRT path renders.

Word timing sources, in order:

1. ``cue["words"]`` — per-word ``{text, start, end}`` persisted at
   transcribe time (services.segmentation). Used only when the words still
   spell the cue's display text: after translation the persisted ASR words
   are source-language tokens, so re-using their timing would burn the
   wrong language. The display text is always authoritative.
2. Estimated split — the cue text's words spread across ``[start, end]``
   in proportion to their length (a long word takes longer to say than a
   short one). Scripts written without spaces (Chinese, Japanese, Thai, Lao,
   Khmer, Burmese) split per character, so a whole line never becomes one
   "word". This is the path for jobs transcribed before word persistence and
   for translated tracks.

Caption styles (``style``):

* ``sweep`` — the classic ``\\kf`` left-to-right fill, one Dialogue per cue.
* ``highlight`` — the line stays white and only the word being spoken turns
  the accent colour.
* ``pop`` — ``highlight`` plus a short vertical bounce on the active word.
  Only ``\\fscy``/``\\bord`` animate: anything that changes a word's width
  would re-centre and shake the whole line.

``highlight`` and ``pop`` emit one Dialogue per word interval. All event
boundaries come from one list of integer centiseconds, so the end of one
interval is exactly the start of the next: no gap (flicker) and no overlap
(double draw).

Dual-layout karaoke is intentionally unsupported (out of scope): callers
must fall back to the line (SRT) burn when the dual layout is requested.
"""

from __future__ import annotations

import re
import unicodedata
from typing import Literal, Optional, Sequence

from services.burn_fonts import BURN_FONT_FAMILY

_WS = re.compile(r"\s+")

#: Scripts written without spaces between words: Hiragana/Katakana, CJK
#: ideographs (+ Ext. A and compatibility), Thai, Lao, Burmese, Khmer.
_NO_SPACE_SCRIPT = re.compile(
    "[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff"
    "\u0e00-\u0e7f\u0e80-\u0eff\u1000-\u109f\u1780-\u17ff]"
)

KaraokeStyle = Literal["sweep", "highlight", "pop"]
KARAOKE_STYLES: tuple[str, ...] = ("sweep", "highlight", "pop")

#: Default ASS canvas. libass scales the script to the real video size, so
#: one reference resolution keeps font/margin proportions stable everywhere.
DEFAULT_PLAY_RES = (1920, 1080)

#: Accent (spoken) and base (not yet / no longer spoken) colours, ASS BGR.
_ACCENT = "&H00E7FF&"
_SWEEP_PRIMARY = "&H0000E7FF"
_WHITE_PRIMARY = "&H00FFFFFF"

_ACTIVE_TAGS = {
    "highlight": f"{{\\1c{_ACCENT}}}",
    "pop": f"{{\\1c{_ACCENT}\\fscy125\\bord4\\t(0,120,\\fscy100\\bord3)}}",
}

_HEADER_TEMPLATE = """[Script Info]
; Generated by VoiceStudio karaoke burn-in
ScriptType: v4.00+
PlayResX: {res_x}
PlayResY: {res_y}
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{font},64,{primary},&H00FFFFFF,&H00101010,&H7F000000,0,0,0,0,100,100,0,0,1,3,1,2,96,96,48,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


def _norm(text: object) -> str:
    return _WS.sub(" ", str(text or "").strip())


def _ass_time(seconds: float) -> str:
    """``H:MM:SS.CC`` (centiseconds) — the ASS event timestamp format."""
    return _ass_time_cs(int(round(float(seconds) * 100)))


def ass_escape(text: str) -> str:
    """Escape a display token for an ASS Dialogue text field.

    Braces would open an override block (user text like ``{\\b1}`` must render
    literally, never execute); newlines become ASS hard line breaks.
    """
    return (
        str(text)
        .replace("{", "\\{")
        .replace("}", "\\}")
        .replace("\r\n", "\\N")
        .replace("\n", "\\N")
        .replace("\r", "\\N")
    )


def _cs(seconds: float) -> int:
    """Karaoke tag duration in centiseconds; ≥1 so a tag never renders as 0."""
    return max(1, int(round(float(seconds) * 100)))


def _graphemes(text: str) -> list[str]:
    """Split into base characters, each carrying its combining marks (Mn/Mc/Me).

    Thai vowel and tone marks, and Burmese/Khmer signs, are combining marks;
    cutting between a base and its mark would draw a lone mark.
    """
    out: list[str] = []
    for ch in text:
        if out and unicodedata.category(ch).startswith("M"):
            out[-1] += ch
        else:
            out.append(ch)
    return out


def split_tokens(text: str) -> list[tuple[str, str]]:
    """Display tokens with the separator that follows each: ``(token, sep)``.

    Whitespace separates words. Inside a word, each character of a script
    written without spaces becomes its own token (joined with ``""``), while
    runs of other characters (the Latin digits of a year next to an ideograph) stay together.
    The last token's separator is ``""``.
    """
    tokens: list[tuple[str, str]] = []
    for word in (w for w in _WS.split(str(text or "").strip()) if w):
        if tokens:
            tokens[-1] = (tokens[-1][0], " ")
        if not _NO_SPACE_SCRIPT.search(word):
            tokens.append((word, ""))
            continue
        run = ""
        for g in _graphemes(word):
            if _NO_SPACE_SCRIPT.match(g):
                if run:
                    tokens.append((run, ""))
                    run = ""
                tokens.append((g, ""))
            else:
                run += g
        if run:
            tokens.append((run, ""))
    return tokens


def estimate_word_times(text: str, start: float, end: float) -> list[dict]:
    """Spread the cue text's tokens over [start, end] by estimated length.

    Each token's share is its character count + 1 (the +1 stands for the
    word onset and the small pause around it, so one-letter words still get
    a visible beat). Per-character tokens of no-space scripts therefore share
    the span evenly. The export fallback for jobs transcribed before per-word
    persistence and for translated tracks (whose persisted words are
    source-language tokens). Each dict carries ``sep``, the text that follows
    the token on screen.
    """
    tokens = split_tokens(text)
    if not tokens:
        return []
    start = float(start)
    span = max(0.0, float(end) - start)
    weights = [len(_graphemes(tok)) + 1 for tok, _ in tokens]
    total = float(sum(weights))
    out: list[dict] = []
    acc = 0
    for (tok, sep), w in zip(tokens, weights):
        t0 = start + span * acc / total
        acc += w
        out.append({"text": tok, "sep": sep, "start": t0, "end": start + span * acc / total})
    return out


def scale_words(
    words: Sequence[dict],
    orig_start: float,
    orig_end: float,
    new_start: float,
    new_end: float,
) -> Optional[list[dict]]:
    """Map word times linearly from [orig_start, orig_end] → [new_start, new_end].

    Used when Smart Fit moves a cue onto the fitted timeline: the persisted
    word times live on the original timeline and must ride along. Returns
    ``None`` when either span is degenerate (caller should drop the words so
    export falls back to an even split over the new span).
    """
    orig_span = float(orig_end) - float(orig_start)
    new_span = float(new_end) - float(new_start)
    if orig_span <= 0 or new_span <= 0:
        return None
    ratio = new_span / orig_span
    out: list[dict] = []
    for w in words:
        try:
            ws = float(w["start"])
            we = float(w["end"])
        except (KeyError, TypeError, ValueError):
            return None
        out.append({
            **w,
            "start": round(float(new_start) + (ws - float(orig_start)) * ratio, 3),
            "end": round(float(new_start) + (we - float(orig_start)) * ratio, 3),
        })
    return out


def _usable_words(cue: dict, text: str) -> Optional[list[tuple[str, float, float]]]:
    """Persisted words, iff well-formed AND they spell the cue's display text."""
    words = cue.get("words")
    if not isinstance(words, list) or not words:
        return None
    clean: list[tuple[str, float, float]] = []
    for w in words:
        if not isinstance(w, dict):
            return None
        wtext = _norm(w.get("text"))
        try:
            ws = float(w["start"])
            we = float(w["end"])
        except (KeyError, TypeError, ValueError):
            return None
        if wtext:
            clean.append((wtext, ws, we))
    if not clean:
        return None
    if _norm(" ".join(t for t, _, _ in clean)) != text:
        return None
    return clean


def _timed_tokens(cue: dict, text: str, start: float, end: float) -> list[tuple[str, str, float]]:
    """``(token, sep, start)`` per display token, clamped into the cue span.

    Starts are clamped and made monotonic so malformed persisted data can
    only mistime the highlight, never corrupt the script.
    """
    persisted = _usable_words(cue, text)
    if persisted:
        raw = [
            (wtext, " " if i + 1 < len(persisted) else "", ws)
            for i, (wtext, ws, _) in enumerate(persisted)
        ]
    else:
        raw = [(w["text"], w["sep"], w["start"]) for w in estimate_word_times(text, start, end)]
    out: list[tuple[str, str, float]] = []
    prev = start
    for wtext, sep, ws in raw:
        ws = min(max(ws, prev), end)
        out.append((wtext, sep, ws))
        prev = ws
    return out


def _sweep_text(tokens: list[tuple[str, str, float]], start: float, end: float) -> str:
    """One Dialogue text field: ``{\\k…}`` lead-in + per-word ``{\\kf…}`` tags.

    Each word's sweep runs until the next word starts (the classic karaoke
    layout — inter-word gaps finish the previous word's fill), and the last
    word sweeps out to the cue end.
    """
    parts: list[str] = []
    lead = tokens[0][2] - start
    if lead > 0.005:
        parts.append(f"{{\\k{_cs(lead)}}}")
    for i, (wtext, sep, ws) in enumerate(tokens):
        nxt = tokens[i + 1][2] if i + 1 < len(tokens) else end
        parts.append(f"{{\\kf{_cs(max(nxt, ws) - ws)}}}{ass_escape(wtext)}{sep}")
    return "".join(parts)


def _line_with_active(tokens: list[tuple[str, str, float]], active: Optional[int], tag: str) -> str:
    parts: list[str] = []
    for i, (wtext, sep, _) in enumerate(tokens):
        body = ass_escape(wtext)
        parts.append(f"{tag}{body}{{\\r}}{sep}" if i == active else f"{body}{sep}")
    return "".join(parts)


def _ass_time_cs(cs: int) -> str:
    h, rem = divmod(max(0, cs), 360000)
    m, rem = divmod(rem, 6000)
    s, c = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{c:02d}"


def _word_events(tokens: list[tuple[str, str, float]], start: float, end: float, tag: str) -> list[str]:
    """One Dialogue per word interval: the whole line, active word tagged.

    Boundaries are rounded to centiseconds ONCE, so consecutive events share
    their edge exactly. The lead-in before the first word shows the line with
    no active word; zero-length intervals are dropped.
    """
    s_cs = int(round(start * 100))
    e_cs = max(s_cs + 1, int(round(end * 100)))
    bounds: list[int] = []
    prev = s_cs
    for _, _, ws in tokens:
        b = min(max(int(round(ws * 100)), prev), e_cs)
        bounds.append(b)
        prev = b
    spans: list[tuple[int, int, Optional[int]]] = []
    if bounds[0] > s_cs:
        spans.append((s_cs, bounds[0], None))
    for i, b in enumerate(bounds):
        nxt = bounds[i + 1] if i + 1 < len(bounds) else e_cs
        spans.append((b, nxt, i))
    return [
        f"Dialogue: 0,{_ass_time_cs(a)},{_ass_time_cs(b)},Default,,0,0,0,,"
        f"{_line_with_active(tokens, active, tag)}"
        for a, b, active in spans
        if b > a
    ]


def build_ass(
    cues: Sequence[dict],
    *,
    dual: bool = False,
    play_res: tuple[int, int] = DEFAULT_PLAY_RES,
    style: KaraokeStyle = "sweep",
) -> str:
    """Build a karaoke ASS script from subtitle cues ({text, start, end, words?}).

    One ``Default`` style in the bundled burn font (see ``services.burn_fonts``).
    ``sweep`` writes one Dialogue per cue; ``highlight``/``pop`` write one per
    word interval. ``dual`` exists for signature parity with the line burn but
    dual-layout karaoke is out of scope — callers must keep the SRT line burn
    for dual, so requesting it here is a contract violation, not a rendering
    mode. An unknown ``style`` is a ValueError (routes validate it first).
    """
    if dual:
        raise ValueError(
            "dual-layout karaoke is not supported; use the line (SRT) burn for dual subtitles"
        )
    if style not in KARAOKE_STYLES:
        raise ValueError(f"unknown karaoke style: {style!r}")
    res_x, res_y = play_res
    lines = [_HEADER_TEMPLATE.format(
        res_x=int(res_x), res_y=int(res_y), font=BURN_FONT_FAMILY,
        primary=_SWEEP_PRIMARY if style == "sweep" else _WHITE_PRIMARY,
    )]
    for cue in cues or []:
        text = _norm(cue.get("text"))
        if not text:
            continue
        start = float(cue["start"])
        end = float(cue["end"])
        if end <= start:
            end = start + 0.1
        tokens = _timed_tokens(cue, text, start, end)
        if style == "sweep":
            lines.append(
                f"Dialogue: 0,{_ass_time(start)},{_ass_time(end)},Default,,0,0,0,,"
                f"{_sweep_text(tokens, start, end)}"
            )
        else:
            lines.extend(_word_events(tokens, start, end, _ACTIVE_TAGS[style]))
    return "\n".join(lines) + "\n"
