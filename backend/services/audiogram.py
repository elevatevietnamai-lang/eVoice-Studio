"""Audiogram clips: a short MP4 of a waveform (plus title and cover) over a
slice of a finished Audiobook / Stories render.

Pure argv/text builders, like ``services.longform_render``: no ffmpeg run, no
filesystem access beyond what the caller passes in. The background is a
``color`` source generated inside ``-filter_complex`` (no ``lavfi`` input, so
``local_inputs_only`` keeps every real input on local protocols), the title is
an ASS line drawn by libass with the bundled burn font (``services.burn_fonts``)
so it looks the same on every OS, and the encode is the same libx264/AAC pair
the dub export already relies on.

Clips are capped at ``MAX_CLIP_SECONDS``: an audiogram is a teaser for social
posts, and a short cap keeps the encode well inside the ffmpeg timeout.
"""

from __future__ import annotations

from typing import Literal, Optional

from services.burn_fonts import BURN_FONT_FAMILY
from services.ffmpeg_utils import local_inputs_only
from services.karaoke_ass import ass_escape

AudiogramShape = Literal["square", "landscape", "vertical"]
SHAPES: dict[str, tuple[int, int]] = {
    "square": (1080, 1080),
    "landscape": (1280, 720),
    "vertical": (1080, 1920),
}
MAX_CLIP_SECONDS = 300.0
MIN_CLIP_SECONDS = 1.0
MAX_TITLE_CHARS = 120
FPS = 25

_BACKGROUND = "0x111827"
_WAVE_COLOUR = "0xFFD400"


def clamp_clip(start: float, duration: float, total: Optional[float] = None) -> tuple[float, float]:
    """Keep the slice inside the program and inside the clip limits.

    ``total`` (the program length, when known) pulls a start past the end back
    so the clip still has ``MIN_CLIP_SECONDS`` of audio.
    """
    start = max(0.0, float(start))
    duration = min(MAX_CLIP_SECONDS, max(MIN_CLIP_SECONDS, float(duration)))
    if total is not None and total > 0:
        start = min(start, max(0.0, float(total) - MIN_CLIP_SECONDS))
        duration = min(duration, max(MIN_CLIP_SECONDS, float(total) - start))
    return round(start, 3), round(duration, 3)


def build_title_ass(title: str, shape: AudiogramShape, duration: float) -> Optional[str]:
    """An ASS script that shows ``title`` across the top for the whole clip.

    Returns None for an empty title. The text is escaped (braces never open
    an override block) and capped at ``MAX_TITLE_CHARS``; libass wraps it.
    """
    text = " ".join(str(title or "").split())[:MAX_TITLE_CHARS]
    if not text:
        return None
    width, height = SHAPES[shape]
    size = max(36, round(min(width, height) * 0.06))
    margin = round(height * 0.08)
    cs = max(1, round(float(duration) * 100))
    h, rem = divmod(cs, 360000)
    m, rem = divmod(rem, 6000)
    s, c = divmod(rem, 100)
    end = f"{h}:{m:02d}:{s:02d}.{c:02d}"
    return (
        "[Script Info]\n"
        "; Generated by VoiceStudio audiogram\n"
        "ScriptType: v4.00+\n"
        f"PlayResX: {width}\nPlayResY: {height}\n"
        "WrapStyle: 0\nScaledBorderAndShadow: yes\n\n"
        "[V4+ Styles]\n"
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n"
        f"Style: Title,{BURN_FONT_FAMILY},{size},&H00FFFFFF,&H00FFFFFF,&H00101010,&H00000000,"
        f"1,0,0,0,100,100,0,0,1,2,0,8,{round(width * 0.08)},{round(width * 0.08)},{margin},1\n\n"
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        f"Dialogue: 0,0:00:00.00,{end},Title,,0,0,0,,{ass_escape(text)}\n"
    )


def build_filter_graph(
    shape: AudiogramShape,
    duration: float,
    *,
    has_cover: bool,
    title_filter: Optional[str] = None,
) -> str:
    """The ``-filter_complex`` graph: background, waveform, cover, title → ``[v]``.

    Input 0 is the audio slice, input 1 the cover (when ``has_cover``).
    ``title_filter`` is a ready ``ass='…':fontsdir='…'`` filter (escaping is
    the caller's job, shared with the subtitle burn) or None for no title.
    """
    width, height = SHAPES[shape]
    wave_w, wave_h = width - (width // 10) * 2, max(120, height // 5)
    wave_y = height - wave_h - height // 10
    parts: list[str] = []
    if has_cover:
        side = min(width, height) // 2
        parts.append("[1:v]split[c1][c2]")
        parts.append(
            f"[c1]scale={width}:{height}:force_original_aspect_ratio=increase,"
            f"crop={width}:{height},boxblur=24:2,eq=brightness=-0.3,setsar=1[bg]"
        )
        parts.append(
            f"[c2]scale={side}:{side}:force_original_aspect_ratio=decrease,setsar=1[cover]"
        )
        # The cover is a still: compose it ONCE, then repeat that frame for the
        # clip, so the blur never runs per frame.
        parts.append(
            f"[bg][cover]overlay=(W-w)/2:(H-h)/2-{height // 12},format=yuv420p,"
            f"loop=loop=-1:size=1:start=0,setpts=N/{FPS}/TB,"
            f"trim=duration={duration:.3f}[base]"
        )
    else:
        parts.append(
            f"color=c={_BACKGROUND}:s={width}x{height}:r={FPS}:d={duration:.3f},setsar=1[base]"
        )
    parts.append(
        f"[0:a]aformat=channel_layouts=mono,"
        f"showwaves=s={wave_w}x{wave_h}:mode=cline:scale=sqrt:rate={FPS}:colors={_WAVE_COLOUR},"
        f"format=rgba[wave]"
    )
    last = "[waved]" if title_filter else "[v]"
    parts.append(f"[base][wave]overlay=(W-w)/2:{wave_y}:shortest=1,format=yuv420p{last}")
    if title_filter:
        parts.append(f"[waved]{title_filter}[v]")
    return ";".join(parts)


def build_audiogram_cmd(
    ffmpeg: str,
    audio_path: str,
    out_path: str,
    *,
    start: float,
    duration: float,
    shape: AudiogramShape = "square",
    cover_path: Optional[str] = None,
    title_filter: Optional[str] = None,
) -> list[str]:
    """Pure argv rendering ``[start, start+duration)`` of ``audio_path`` to MP4."""
    if shape not in SHAPES:
        raise ValueError(f"unknown audiogram shape: {shape!r}")
    cmd = [
        ffmpeg, "-y", "-hide_banner", "-loglevel", "error",
        "-ss", f"{float(start):.3f}", "-t", f"{float(duration):.3f}", "-i", str(audio_path),
    ]
    if cover_path:
        cmd += ["-i", str(cover_path)]
    cmd += [
        "-filter_complex",
        build_filter_graph(shape, duration, has_cover=bool(cover_path), title_filter=title_filter),
        "-map", "[v]", "-map", "0:a",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-pix_fmt", "yuv420p",
        "-r", str(FPS),
        "-c:a", "aac", "-b:a", "160k",
        "-t", f"{float(duration):.3f}", "-shortest",
        "-movflags", "+faststart", "-f", "mp4", str(out_path),
    ]
    return local_inputs_only(cmd, tool="ffmpeg")
